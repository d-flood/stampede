import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { expect, test } from '../e2e/fixtures.ts';
import { Director } from './record.ts';
import { configure, project } from './stage.ts';

test('branches, LazyGit keys, stash and publish', async ({ browser, baseURL }) => {
	test.setTimeout(180_000);
	const root = process.env.STAMPEDE_E2E_ROOT!;
	const path = project(root, 'tidepool');
	const git = (...args: string[]) => execFileSync('git', ['-C', path, ...args], { encoding: 'utf8' }).trim();
	const origin = join(root, 'origin.git');
	execFileSync('git', ['init', '-q', '--bare', '-b', 'main', origin]);
	git('remote', 'add', 'origin', origin);
	git('push', '-q', '-u', 'origin', 'main');
	const edit = (file: string, before: string, after: string) => {
		const text = readFileSync(join(path, file), 'utf8');
		expect(text).toContain(before);
		writeFileSync(join(path, file), text.replace(before, after));
	};
	edit('src/lib/components/NoteList.svelte', "{ month: 'short', day: 'numeric' }", "{ dateStyle: 'medium', timeStyle: 'short' }");
	edit('README.md', '- Pin the notes you come back to\n', '- Pin the notes you come back to\n- See when each note last changed\n');

	const desktop = await (await browser.newContext({ baseURL, viewport: { width: 1280, height: 800 }, deviceScaleFactor: 2, colorScheme: 'dark' })).newPage();
	await configure(desktop, root, []);
	await desktop.goto('/');
	await desktop.getByRole('navigation', { name: 'Projects' }).getByRole('button', { name: 'Open Project' }).click();
	await desktop.getByRole('option', { name: /\/tidepool$/ }).click();
	await expect(desktop.getByRole('dialog')).toBeHidden();
	const sidebar = desktop.getByRole('complementary', { name: 'Sidebar' });
	if (!(await sidebar.isVisible())) await desktop.getByRole('button', { name: 'Sidebar' }).click();
	await sidebar.getByRole('button', { name: 'README.md', exact: true }).click();
	await desktop.getByRole('radio', { name: 'Preview', exact: true }).click();
	await sidebar.getByRole('button', { name: 'Git', exact: true }).click();
	const changes = sidebar.getByRole('list', { name: 'Changes', exact: true });
	await expect(changes.getByRole('button', { name: 'NoteList.svelte', exact: true })).toBeVisible();
	await expect(sidebar.getByText('origin/main')).toBeVisible();
	await desktop.mouse.move(900, 500);

	const director = new Director('git');
	await director.record('desktop', desktop);
	await director.hold(1);
	director.mark('desktop', 'start');
	await director.focus('desktop', 'sidebar', sidebar);
	await director.click('desktop', sidebar.getByRole('button', { name: 'Branch main' }));
	const picker = desktop.getByRole('dialog', { name: 'Switch branch' });
	await director.focus('desktop', 'picker', picker);
	await director.type('desktop', picker.getByRole('combobox'), 'note-times');
	const create = picker.getByRole('option', { name: 'Create branch note-times' });
	await expect(create).toBeVisible();
	await director.hold(0.4);
	await director.click('desktop', create, 0.5);
	await expect(picker).toBeHidden();
	await expect(sidebar.getByRole('button', { name: 'Branch note-times' })).toBeVisible();
	await director.hold(0.8);
	director.mark('desktop', 'branched');

	const row = changes.getByRole('button', { name: 'NoteList.svelte', exact: true });
	await director.click('desktop', row);
	const diff = desktop.locator('.diff:not([hidden])').filter({ has: desktop.locator('.sides') });
	await expect(diff.locator('.cm-merge-b .cm-changedLine').first()).toBeVisible();
	await director.hold(1);
	await director.click('desktop', desktop.getByRole('tab', { name: 'README.md' }), 0.5);
	await row.focus();
	await director.rest('desktop', desktop, 900, 500);
	await director.hold(0.8);
	director.keys('desktop', 'Space');
	await desktop.keyboard.press('Space');
	const staged = sidebar.getByRole('list', { name: 'Staged Changes' });
	await expect(staged.getByRole('button', { name: 'NoteList.svelte', exact: true })).toBeVisible();
	await director.hold(0.7);
	director.keys('desktop', 'c');
	await desktop.keyboard.press('c');
	const message = sidebar.getByRole('textbox', { name: 'Commit message' });
	await expect(message).toBeFocused();
	await director.type('desktop', message, 'Show when each note changed');
	await director.hold(0.4);
	director.keys('desktop', 'Ctrl + Enter');
	await desktop.keyboard.press('Control+Enter');
	await expect(staged).toHaveCount(0);
	expect(git('log', '-1', '--format=%s')).toBe('Show when each note changed');
	director.mark('desktop', 'committed');
	await director.hold(0.8);

	await desktop.keyboard.press('Escape');
	await expect(sidebar.locator('[data-key]:focus')).toHaveCount(1);
	director.keys('desktop', 's');
	await desktop.keyboard.press('s');
	const stashes = sidebar.getByRole('list', { name: 'Stashes' });
	await expect(stashes.getByRole('listitem')).toHaveCount(1);
	await expect(sidebar.getByText('No uncommitted changes')).toBeVisible();
	director.mark('desktop', 'stashed');
	await director.hold(1);

	const publish = sidebar.getByRole('button', { name: 'Publish Branch' });
	await director.click('desktop', publish);
	await expect(sidebar.getByText('origin/note-times')).toBeVisible();
	expect(execFileSync('git', ['-C', origin, 'log', '-1', '--format=%s', 'note-times'], { encoding: 'utf8' }).trim()).toBe('Show when each note changed');
	director.mark('desktop', 'published');
	await director.hold(0.8);
	const commits = sidebar.getByRole('list', { name: 'Commits' });
	await expect(commits).toContainText('Show when each note changed');
	await director.hover('desktop', commits.getByText('Show when each note changed'), 0.5);
	await director.hold(1.8);
	director.mark('desktop', 'end');
	await director.finish();
});
